def _mask_quoted_segments(text: str) -> str:
    """F-53-2 (Lead, liveness-проба D-0093, 2026-07-23, живой ложный
    БЛОК): `grep -c ">" logs/routing-log.jsonl` (read-only) БЫЛ
    заблокирован -- кавычённый ">" (аргумент-строка grep'а, НЕ
    редирект) считался формой записи в одном statement с журнальной
    целью. ФИКС: перед проверкой редиректа `>`/`>>` маскируем
    содержимое одинарных/двойных кавычек (regex ДОСЛОВНО того же
    char-класса, что COMMIT_MESSAGE_ARG_RE выше -- уже проверенный в
    этом файле паттерн для двойных кавычек с escape-последовательностями).
    Незакрытая кавычка НЕ матчится -- текст остаётся немаскированным
    (fail-safe В СТОРОНУ детекта, тот же принцип, что и остальной файл,
    см. test_v2_unclosed_quote_in_non_git_write_command_still_triggers).
    Применяется ТОЛЬКО к проверке редиректа -- printf/echo/sed -i/tee/
    open-write-mode индикаторы проверяются на ИСХОДНОМ тексте (DoD
    задачи: "прочие индикаторы форм... не задеваются")."""
    return QUOTED_SEGMENT_RE.sub(lambda m: " " * len(m.group(0)), text)


