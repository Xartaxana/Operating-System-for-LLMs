def _mask_heredoc_bodies(text: str) -> str:
    """К3.1 (v6, F.3) -- живой корпусный FP (K3.3, 2026-08-20): маскирует
    ТЕЛО ЛЮБОГО heredoc'а (не только git-commit -- в отличие от
    `_strip_commit_messages`, здесь НЕТ git-гарда и НЕТ исключения
    python-heredoc-опенера) -- ПЕРЕИСПОЛЬЗУЕТ `COMMIT_HEREDOC_RE`
    (D-0043: тот же паттерн "опенер + тело + закрывающая строка", сам
    регекс НЕ git-специфичен -- git-специфичность живёт в ГАРДАХ вокруг
    `_strip_commit_messages`/`_heredoc_belongs_to_git_commit`, не в
    паттерне). Опенер-строка (группы 1+4) СОХРАНЯЕТСЯ дословно -- если
    это САМ `python -<<DELIM`, `PY_HEREDOC_RE` по-прежнему матчит его;
    ТЕЛО (группа 5) заменяется пробелами ТОЙ ЖЕ длины (сохраняет
    позиции, тот же принцип, что `_mask_quoted_segments`).

    ЧЕСТНО О СМЫСЛЕ МАСКИ -- "ОБЁРТОЧНАЯ ДЫРА" (ПЕРЕСДАЧА, п.1 --
    прежняя формулировка называла тело heredoc'а «данными» без
    оговорки, что для ИСПОЛНЯЮЩИХ обёрток это неверно факту): маска
    снимает ОПРЕДЕЛЁННОСТЬ (`pyc_certain`) с ЛЮБОГО heredoc-тела -- она
    НЕ различает прозу (текст commit-сообщения) от РЕАЛЬНО ИСПОЛНЯЕМОГО
    кода. Замер критика (ПЕРЕСДАЧА, builder независимо перепроверил):
    `bash <<'EOF' ... python -c "print(1)" ... EOF`, `sh <<EOF ... EOF`,
    `cat <<EOF | bash`, `ssh host <<EOF`, `docker exec -i c bash <<EOF`
    -- во ВСЕХ пяти формах тело heredoc'а РЕАЛЬНО подаётся нижестоящему
    интерпретатору и ИСПОЛНЯЕТСЯ; маска гасит их `pyc_certain` НАРАВНЕ с
    прозой git-commit-сообщения -- результат ТОТ ЖЕ WARN, что и для
    настоящего упоминания-как-данных, а не DENY, которого заслуживает
    реальный вызов. ТОТ ЖЕ эффект даёт КАВЫЧКОВАЯ маска
    (`_mask_quoted_segments`, не heredoc) на формах `bash -c
    "python -c '...'"`, `sh -c '...'`, `eval "..."` -- токен "python -c"
    стоит ВНУТРИ кавычек-аргумента обёртки, маскируется как данные, хотя
    обёртка его реально исполняет.

    Это ИЗВЕСТНАЯ, НЕУСТРАНЁННАЯ дыра (не чинится этой задачей -- см.
    docs/tasks/2026-08-20_calibration-8-remediation.md узел F, п.5:
    блок и без того нодж, Р16 уже оставил вне охвата python3/py/pwsh -c,
    закрывать ОДНУ из четырёх дыр интерпретаторным гардом непропорционально
    дорого относительно выгоды, Rule #1 -- решение оператора, вопрос
    "нодж или enforcement" возвращён целиком вместе с Р16). Запинена
    тестами test_p6_wrapper_*_not_covered_known_limitation в
    tools/test_hygiene_gate.py. СМЯГЧЕНИЕ ЕСТЬ (запинено тем же набором
    тестов): широкий сигнал `pyc` (`_is_python_dash_c`) читает СЫРОЙ,
    НЕмаскированный текст -- для heredoc-форм он ВИДИТ токен "python -c"
    в теле буквально (PY_DASH_C_RE матчит по СЫРОЙ команде) и для
    кавычковых форм тоже видит токен вне квотирования на СВОЁМ
    (немаскированном) проходе -- в обоих случаях результат WARN
    (MSG_PYTHON_DASH_C), НЕ тишина: деградация до WARN, а не слепота.

    Живой репро координатора (K3.3, дословно): `git add ... && git
    commit -F - <<'EOF'` с телом сообщения, упоминающим "класс python
    -c/heredoc переводится в deny" КАК ПРОЗУ -- РЕАЛЬНЫЙ, легальный git
    commit; без этой маски `_is_python_dash_c_certain` денала бы его
    (PY_DASH_C_RE матчит "python -c" ВНУТРИ тела heredoc'а НЕ-python
    команды, что не является shell-квотированием, `_mask_quoted_segments`
    его не видит). `pyc` (широкий сигнал, К3.1) читает СЫРОЙ текст и НЕ
    маскируется -- такая команда попадает в WARN (MSG_PYTHON_DASH_C),
    не в тишину и не в DENY -- Р17 (полная симметрия с 2>&1): heredoc-
    body-упоминание -- НЕОДНОЗНАЧНАЯ форма.

    Порядок вызова (см. `_is_python_dash_c_certain`): heredoc-маска
    ПЕРЕД `_mask_quoted_segments` -- кавычки ВНУТРИ heredoc-тела (сырой
    прозы) могли бы иначе ложно "спариться" с кавычками СНАРУЖИ
    heredoc'а (та же логика порядка, что в `_strip_commit_messages`,
    "(1) message, (2) heredoc")."""
    return COMMIT_HEREDOC_RE.sub(
        lambda m: m.group(1) + m.group(4) + " " * len(m.group(5)), text
    )


# М2-3 (docs/tasks/2026-08-25_kopilka-wave-spec.md, "БИЛДЕР М2", Ф3
# вердикта критика t-605): `_mask_heredoc_bodies` (через
# `COMMIT_HEREDOC_RE.sub`, `.*?^\3\s*$` с DOTALL/MULTILINE) КВАДРАТИЧНА
# на форме "повторённые опенеры `python - <<DELIM` БЕЗ закрывателя" --
# при каждом опенере регекс безуспешно бэктрекает до КОНЦА текста в
# поисках несуществующего закрывателя, прежде чем сдвинуться к
# следующему опенеру (замер ДО фикса, предсуществующая: 0.074с/9.6КБ,
# 1.165с/38КБ, 8.363с/96КБ -- ~×4 роста при ~×4 роста размера на
# верхнем скачке, не линейно). ФИКС: дешёвый O(n) предфильтр БЕЗ
# backtracking (`command.count("<<")`, та же простая substring-проверка,
# что `_collect_redirect_signal` уже использует для class ` 2>&1`) --
# сверх `MAX_HEREDOC_OPENERS` дорогой regex-проход (`_mask_heredoc_bodies`)
# вовсе НЕ вызывается: ранний консервативный выход `certain=False`.
# НАПРАВЛЕНИЕ КОНСЕРВАТИВНО (deny НЕ расширяется, I2-инвариант цел):
# `certain=False` -> `_classify_pyc_payload` вернёт "U" (unclassified,
# см. её докстринг) -> `_decide_v5` даёт СТАРОЕ безусловное WARN-
# поведение (MSG_PYTHON_DASH_C), НЕ deny -- гигантская форма ДО фикса
# теоретически могла бы денаиться (если бы пережила квадратичный проход
# и токен остался бы вне масок), ПОСЛЕ фикса -- гарантированно WARN, не
# хуже, чем до промоции К3 вовсе. Порог 64 -- заведомо выше любого
# реального heredoc-контента одной команды (нормальная команда несёт 0-2
# heredoc'а); ложное срабатывание предфильтра на НЕ-heredoc "<<"
# (напр. bit-shift в строковом литерале) только УСИЛИВАЕТ консервативность
# (лишний False вместо True), не ослабляет её.
#
# I2-ИНВАРИАНТ (спека, буквально, ИСТОРИЧЕСКИ на 2026-08-25): все
# существующие deny-тесты hygiene_gate остаются зелёными БЕЗ правки ИХ
# ТЕЛ -- этот предфильтр не меняет результат ни для одной существующей
# фикстуры (все они на порядки меньше 64 heredoc-опенеров в одной
# команде); подтверждено полным прогоном tools/test_hygiene_gate.py
# (см. witness отчёта). ПОМЕТКА (t-651, 2026-08-27): I2 как ОБЩИЙ
# инвариант СУПЕРСИДЕН (см. блок PYC_DENY_ENABLED ниже) -- но ИМЕННО
# ЭТОТ узкий вывод ("certain=False -> U -> WARN, не deny") остаётся
# верным и ПОСЛЕ, т.к. класс "U" не денает НИ ПРИ старом, НИ при новом
# условии `pyc_deny` -- ничего в поведении этого предфильтра менять
# не потребовалось.
MAX_HEREDOC_OPENERS = 64


def _is_python_dash_c_certain(command: str) -> bool:
    """К3.1 (v6, F.3): ОТДЕЛЬНЫЙ, НОВЫЙ сигнал определённости для
    класса (в) -- НЕ путать с широким `_is_python_dash_c` (ключ `pyc`
    в `_collect_v5_signals`, сохраняет СЕГОДНЯШНИЙ смысл "класс
    сработал вообще" БЕЗ ИЗМЕНЕНИЙ, читает СЫРУЮ, немаскированную
    команду -- `permission_audit.classify_hygiene()` читает `pyc` ПО
    ИМЕНИ и сравнивает 4-меточный контракт с baseline чека 25,
    переопределение смысла ключа молча сломало бы это сравнение).

    Р13=(а): токен "python -c"/"python - <<" денается ТОЛЬКО если
    переживает И `_mask_heredoc_bodies` (см. её докстринг -- живой
    корпусный FP, heredoc-body-упоминание в НЕ-python команде), И
    `_mask_quoted_segments` -- т.е. это РЕАЛЬНЫЙ вызов (сам токен НЕ
    внутри `'...'`/`"..."` и НЕ внутри ЧУЖОГО heredoc-тела), не
    упоминание как данные (напр. `git commit -m "run python -c to
    test"` -- "python -c" целиком внутри кавычек -m-значения,
    маскируется, pyc_certain=False). ОБЫЧНЫЙ вызов `python -c "код"`
    ОСТАЁТСЯ определённым: кавычки здесь -- вокруг АРГУМЕНТА -c, а не
    вокруг самого токена "python -c" (он стоит ПЕРЕД кавычкой,
    маскировка его не трогает) -- это и есть цель промоции (К3,
    calibration #8): подавляющее большинство реальных вызовов
    `python -c "..."` синтаксически ВСЕГДА несут кавычки вокруг
    payload'а, это не делает их "неоднозначными". РЕАЛЬНЫЙ heredoc-
    опенер `python - <<DELIM` ТОЖЕ остаётся определённым: маска
    сохраняет опенер-строку (группы 1+4), ТОЛЬКО тело заменяется
    пробелами -- собственный `<<` heredoc'а не гасит собственную
    определённость.

    М2-3 (t-605 Ф3): ДЕШЁВЫЙ предфильтр (`command.count("<<")`, O(n),
    без backtracking) СНАЧАЛА -- сверх `MAX_HEREDOC_OPENERS` дорогой
    `_mask_heredoc_bodies` (квадратичный на форме "опенеры без
    закрывателя") вовсе не зовётся -- ранний консервативный выход
    `False` (см. блок-докстринг константы выше за полное обоснование
    направления и инварианта)."""
    if command.count("<<") > MAX_HEREDOC_OPENERS:
        return False
    masked = _mask_quoted_segments(_mask_heredoc_bodies(command))
    return bool(PY_DASH_C_RE.search(masked) or PY_HEREDOC_RE.search(masked))


