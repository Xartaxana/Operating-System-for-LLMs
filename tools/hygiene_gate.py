def _collect_redirect_signal(command: str) -> dict:
    """Ф2 (координатор, финальный фикс): вычисляет `present`/`certain`
    для класса ` 2>&1` по МАСКИРОВАННОМУ (через `_mask_quoted_segments`,
    та же функция, что уже несёт класс (г) ниже -- НЕ вторая реализация,
    D-0043) тексту -- см. докстринг раздела выше за полный разбор трёх
    веток и обоснование замены списка интерпретаторов кавычками."""
    masked = _mask_quoted_segments(command)
    present = " 2>&1" in masked
    if not present:
        return {"present": False, "certain": False}
    ambiguous_heredoc = "<<" in masked
    return {"present": True, "certain": not ambiguous_heredoc}


