# test_v2_git_reset_not_in_whitelist_still_triggers. Сами пины охраняют
# СОВПАДЕНИЕ ("git rm"/"git reset" не входят в этот перечень, значит
# ветка read-only-головы их не касается), а НЕ содержательную гарантию
# защиты журнала от удаления: замер критика (ПЕРЕСДАЧА) -- ТОТ ЖЕ
# `git rm logs/routing-log.jsonl` БЕЗ редиректа проходит МОЛЧА (нет `>`
# -- `_has_write_form` не матчит ничего), и так же молчат `rm`, `mv`,
# `truncate -s 0 <журнал>`, PowerShell `Remove-Item`, `git checkout --
# <журнал>` -- НИ ОДНА форма удаления/перезаписи журнала мимо
# редиректа/printf/echo/sed-i/tee/open-write НЕ детектируется этим
# гейтом вообще. DENY на `git rm ... > /tmp/x` держится ИСКЛЮЧИТЕЛЬНО на
# несвязанном `>` (случайный редирект СТОРОННЕГО вывода в том же
# statement, не на распознавании удаления журнала) -- принципиальной
# защиты журнала ОТ УДАЛЕНИЯ в этом файле НЕТ; это ИЗВЕСТНЫЙ, НЕ
# закрытый этой задачей пробел, в очередь (см. HANDOFF отчёта builder'а,
# docs/tasks/2026-08-20_calibration-8-remediation.md узел F).
#
# "sed" здесь БЕЗ различения -n/-i -- безопасно: sed -i
# сама по себе уже отдельно триггерит через SED_INPLACE_RE независимо
# от этого списка, попадание "sed" в read-only-голову не гасит её.
_READ_ONLY_HEAD_RE = re.compile(r"^\s*(?:grep|rg|cat|head|tail|wc|sed)\b", re.IGNORECASE)


def _redirect_targets_journal(text: str) -> bool:
    """F.3 (ремедиация калибровки №8, узел F.3, живой ложный БЛОК
    2026-08-20): для statement'ов с READ-ONLY головой (`_READ_ONLY_HEAD_RE`)
    `>` больше НЕ считается формой ЖУРНАЛЬНОЙ записи просто по своему
    ПРИСУТСТВИИ где-то в statement'е -- проверяется, что редирект РЕАЛЬНО
    ЦЕЛИТСЯ в журнал (та же цель, что `_has_journal_target` уже
    распознаёт: подстрока "routing-log" ИЛИ `logs/*.jsonl`), а не
    куда-то ещё.

    Живой репро (координатор, дословно): `grep -c "reserve_engaged"
    logs/routing-log.jsonl tools/*.py 2>/dev/null | grep -v ":0"` --
    ЧТЕНИЕ журнала (grep -c), денилось из-за `>` внутри `2>/dev/null`
    (редирект STDERR В НИКУДА, не про журнал вовсе). До этого фикса
    `_has_write_form` матчила ЛЮБОЙ `>` в statement'е (`">" in
    redirect_check_text`), не спрашивая цель -- цена: journal-target
    ГДЕ-ТО в том же statement (напр. как read-only аргумент grep'а/
    cat'а/head'а/tail'а/wc'а/`sed -n`) + ЛЮБОЙ несвязанный редирект
    (`2>/dev/null`, `2>&1`, `> /tmp/out.txt`) уже давали ложный БЛОК.

    Механизм (вызывается ТОЛЬКО когда `_READ_ONLY_HEAD_RE` матчит --
    см. `_has_write_form`): находит позиции РЕАЛЬНЫХ (не в кавычках)
    операторов `>`/`>>` на замаскированном (`_mask_quoted_segments`)
    тексте -- длина маскировки СОХРАНЯЕТ позиции символов 1-в-1 с
    исходным текстом (маска -- пробелы той же длины), поэтому индексы
    валидны для ОБОИХ текстов. Для каждого найденного оператора: (1)
    `>&N` (fd-дублирование, напр. `2>&1`) -- НЕ файловый таргет вовсе,
    пропускается; (2) иначе цель читается из ИСХОДНОГО (не
    замаскированного) текста сразу после оператора -- кавычённая (до
    парной закрывающей) или голая (до пробела/`;`/`&`/`|`/перевода
    строки); (3) цель проверяется ТОЙ ЖЕ функцией `_has_journal_target`
    (D-0043 -- не вторая реализация распознавания цели). Если ХОТЯ БЫ
    ОДИН редирект статемента целится в журнал -- True; если ни один --
    False (утечка через `>` в направлении, не связанном с журналом,
    реальной записью в журнал не является).

    Известное ограничение (не устранено, не в объявленном evidence):
    цель проверяется ТОЛЬКО как ТЕКСТ (та же дисциплина, что и
    остальной файл) -- динамическая переменная в качестве цели
    (`echo x > $F`) уже честно не распознаётся ни здесь, ни
    `_has_journal_target` (см. существующий тест
    test_vg5_variable_path_not_recognized_no_block_honest_limitation).

    ВТОРОЕ известное ограничение (ПЕРЕСДАЧА, п.4 -- перечень
    `_READ_ONLY_HEAD_RE` НЕПОЛОН; замер критика -- живые ложные DENY на
    ЧИТАЮЩИХ вызовах, чья голова statement'а НЕ входит в этот перечень:
    такой statement идёт ДЕФОЛТНЫМ путём `_has_write_form` (голое
    присутствие `>`/`2>...` где-то в тексте, БЕЗ проверки цели
    редиректа), поэтому журнальная цель + НЕСВЯЗАННЫЙ редирект в том же
    statement денают, хотя вызов read-only):
      - ЦЕЛИКОМ PowerShell-ось -- `Get-Content ...routing-log.jsonl
        2>$null`, `Select-String -Path ...routing-log.jsonl ... 2>$null`
        (хук обслуживает PowerShell наравне с Bash, перечень выше не
        содержит НИ ОДНОГО PowerShell-командлета чтения);
      - читалки `ls`, `jq`, `sort`, `cut`, `diff`, `nl`, `tac`,
        `md5sum`, `stat`, `du`, `file`;
      - ПРЕФИКСНЫЕ обёртки над РАЗРЕШЁННОЙ головой -- `sudo grep ...`,
        `time grep ...` денятся (голова statement'а -- "sudo"/"time", не
        "grep"), тогда как голый `grep ...` с ТЕМ ЖЕ несвязанным
        редиректом молчит;
      - git-читалки ВНЕ whitelist `GIT_STATEMENT_RE` -- `git blame`,
        `git ls-files`, `git grep`, `git check-ignore`;
      - отдельно: `python <скрипт> <путь-журнала> 2>/dev/null` --
        САНКЦИОНИРОВАННЫЙ путь отхода (Р15=(а), см. докстринг раздела
        v6 выше "ЧТО ОСТАЁТСЯ ЛЕГАЛЬНЫМ") САМ попадает под этот
        неисправленный ложный блок, если несёт несвязанный редирект.
    Все формы воспроизведены builder'ом этой пересдачи эмпирически (не
    заявлены со слов критика без проверки). Не устраняется этой задачей
    (non-goals: не расширять токен-наборы за пределы явно данных спекой)
    -- в очередь, см. HANDOFF отчёта builder'а,
    docs/tasks/2026-08-20_calibration-8-remediation.md узел F."""
    masked = _mask_quoted_segments(text)
    for m in _REDIRECT_OP_RE.finditer(masked):
        end = m.end()
        if masked[end:end + 1] == "&":
            continue
        pos = end
        while pos < len(text) and text[pos] in " \t":
            pos += 1
        qm = _REDIRECT_TARGET_QUOTED_RE.match(text, pos)
        if qm:
            target = qm.group(0).strip("\"'")
        else:
            bm = _REDIRECT_TARGET_BARE_RE.match(text, pos)
            target = bm.group(0) if bm else ""
        if target and _has_journal_target(target):
            return True
    return False


def _has_write_form(text: str) -> bool:
    """VG-5: формы шелл-ЗАПИСИ -- редирект `>`/`>>`, printf/echo
    (как раньше), + sed -i (in-place), tee, python open(...,'w'/'a'/
    'x') (новое, см. докстринг раздела v3 -- DoD п.1 требует блок и на
    этих формах). F-53-2: редирект `>` проверяется на ТЕКСТЕ С
    ЗАМАСКИРОВАННЫМИ кавычками (_mask_quoted_segments) -- кавычённый
    `>` (данные аргумента, не shell-редирект) больше не считается.
    F.3 (ремедиация калибровки №8): для statement'ов с READ-ONLY
    головой (`_READ_ONLY_HEAD_RE` -- grep/rg/cat/head/tail/wc/sed)
    редирект `>`/`>>` теперь ДОЛЖЕН ЦЕЛИТЬСЯ В ЖУРНАЛ
    (`_redirect_targets_journal`), не просто присутствовать где-то в
    statement'е -- см. её докстринг за живой репро и полный разбор.
    ДЛЯ ВСЕХ ОСТАЛЬНЫХ ГОЛОВ (в т.ч. `git rm`/`git reset` -- НЕ входят
    в git-whitelist `_mask_git_statements`, и в этот read-only-перечень
    тоже) поведение `>` НЕ МЕНЯЕТСЯ -- буквальное присутствие где-то в
    statement'е по-прежнему считается формой записи (регресс-пины
    test_v2_git_rm_not_in_whitelist_still_triggers_if_it_would_otherwise/
    test_v2_git_reset_not_in_whitelist_still_triggers, тела которых не
    правятся).

    ПЕРЕСДАЧА (координатор, БЛОКЕР 2): PowerShell-командлеты записи
    (Add-Content/Set-Content/Out-File, _PS_WRITE_CMDLET_RE) добавлены
    ЗА ВЫКЛЮЧАТЕЛЕМ `V5_ENABLED` -- класс (г) уже ЖИВОЙ БЛОК (VG-5, до
    этой задачи), правка ВНЕ выключателя изменила бы его поведение в
    момент СОХРАНЕНИЯ для V5_ENABLED=False (нарушая M8 этой задачи).
    Читает модульный global на каждый вызов (тот же паттерн, что
    decide()/_decide_v5) -- НЕ отдельная `_has_write_form_v5`, ЧТОБЫ
    `_is_journal_bypass`/статемент-скоупинг не дублировались (D-0043):
    ОДИН детектор, ОДНА точка входа для V4 и V5 обеих."""
    if _READ_ONLY_HEAD_RE.match(text):
        redirect_hit = _redirect_targets_journal(text)
    else:
        redirect_hit = ">" in _mask_quoted_segments(text)
    if (
        redirect_hit
        or PRINTF_ECHO_RE.search(text)
        or SED_INPLACE_RE.search(text)
        or TEE_RE.search(text)
        or OPEN_WRITE_MODE_RE.search(text)
    ):
        return True
    return bool(V5_ENABLED and _PS_WRITE_CMDLET_RE.search(text))


def _is_journal_bypass(command: str) -> bool:
    """VG-5: СТЕЙТМЕНТ-СКОУПИРОВАНО (было -- проверка целиком по
    заскрабленной команде без учёта разделителей, см. докстринг
    раздела v3, "СТЕЙТМЕНТ-СКОУПИНГ" -- живой FP builder'а этой
    задачи: `cat logs/routing-log.jsonl; echo done` триггерил ДО этой
    правки, хотя echo пишет НЕ в журнал). Триггер -- только если ОДИН
    И ТОТ ЖЕ statement несёт и цель (_has_journal_target), и форму
    записи (_has_write_form).

    Ф1 (докстринг queue8-closure.md/kopilka-wave-spec.md, критик волны
    "fit_with_fixes", СОСЕД М2-3 -- ТОТ ЖЕ COMMIT_HEREDOC_RE, ДРУГОЙ
    путь вызова): `_strip_commit_messages()` квадратична на командах,
    несущих "git commit" ОДНОВРЕМЕННО с множеством незакрытых heredoc-
    опенеров -- ТА ЖЕ причина, что М2-3 закрыл для
    `_is_python_dash_c_certain` (COMMIT_HEREDOC_RE.sub бэктрекает до
    конца текста на каждый опенер без закрывателя). Замер критика:
    0.12/0.50/2.23с при n=500/1000/2000 опенеров (с "git commit" в
    команде); негативный контроль -- ТА ЖЕ форма БЕЗ "git commit"
    0.0035с (`_strip_commit_messages` тогда рано выходит по
    GIT_COMMIT_RE-гарду, дорогой путь не достигается вовсе -- значит
    гарантия "не квадратична НИКОГДА" не нужна, нужна ТОЛЬКО для ветки
    "git commit" + гигантский heredoc).

    ТОТ ЖЕ предфильтр/кап, что MAX_HEREDOC_OPENERS у М2-3 (D-0043 --
    один порог, одна константа, не вторая копия числа): сверх лимита --
    КОНСЕРВАТИВНЫЙ путь, bypass-проверка НЕ ВЫПОЛНЯЕТСЯ вовсе, эта
    функция возвращает False (то же самое, что "not bypass" -- ТОТ ЖЕ
    класс направления, что М2-3: журнальный DENY класса (г) НЕ
    РАСШИРЯЕТСЯ формой, для которой раньше был бы честный, но дорогой
    ответ -- гигантская форма, которая ДО фикса теоретически могла бы
    (пережив квадратичный проход) дать True, ПОСЛЕ фикса гарантированно
    даёт False -- deny не приобретает новых срабатываний, только теряет
    возможные (не факт, что они вообще были -- предфильтр НЕ утверждает
    "раньше был True", только "мы больше не считаем")."""
    if command.count("<<") > MAX_HEREDOC_OPENERS:
        return False
    scrubbed = _mask_git_statements(_strip_commit_messages(command))
    return any(
        _has_journal_target(stmt) and _has_write_form(stmt)
        for stmt in _statements(scrubbed)
    )


def _collect_warn_classes(command: str) -> list[str]:
    """Классы (а)/(б)/(в) -- НЕ меняются этой задачей (non-goals VG-5:
    "не менять прочие WARN-классы"), проверяются по ИСХОДНОЙ (не
    заскрабленной) команде, как и до этой правки."""
    triggered = []
    if _is_cd_prefix(command):
        triggered.append(MSG_CD_PREFIX)
    # v4 (П4): "2>&1" внутри вырезаемого текста -m/--message commit-
    # сообщения не должно триггерить -- см. докстринг раздела v4,
    # "ФИКС (2)".
    if " 2>&1" in _strip_commit_message_arg_only(command):
        triggered.append(MSG_REDIRECT_STDERR)
    if _is_python_dash_c(command):
        triggered.append(MSG_PYTHON_DASH_C)
    return triggered


def _decide_v4(command: str) -> tuple[int, dict | None]:
    """V5_ENABLED=False -- буквальное СТАРОЕ тело decide() этого файла
    (VG-5/v2/v3/v4/F1/F-53/F-53-2), ПЕРЕНЕСЁННОЕ БЕЗ функциональных
    изменений (только имя функции и то, что `command` теперь параметр,
    а не читается заново из payload -- см. decide() ниже, который уже
    извлёк и провалидировал его). exit_code ВСЕГДА 0 -- VG-5 НЕ меняет
    этот инвариант (см. докстринг раздела v3, "EXIT-КОД БЕЗ ИЗМЕНЕНИЙ"):
    блокировка класса (г) сигналится ИСКЛЮЧИТЕЛЬНО через
    hookSpecificOutput.permissionDecision="deny" в JSON на stdout, не
    через код возврата процесса. Возвращает (0, None) на тихий пропуск,
    (0, dict) -- dict уже готов к json.dumps на stdout при совпадении
    хотя бы одного класса."""
    # VG-5: класс (г) -- БЛОК, проверяется ПЕРВЫМ и отдельно от
    # WARN-классов (а)/(б)/(в), которые остаются как были.
    #
    # F-53 (критик, доп. к VG-5, 2026-07-23) BELT-AND-SUSPENDERS:
    # permissionDecision="deny" форензически обоснован (докстринг
    # раздела v3), но в репо на момент правки НЕТ ЖИВОГО прецедента
    # deny -- единственный живой блокирующий гейт (dispatch_gate.py)
    # блокирует через exit-код 2, не через этот JSON-канал. Если deny
    # харнессом не исполняется, класс (г) деградирует НЕ в прежний
    # WARN, а в ПОЛНУЮ ТИШИНУ (permissionDecisionReason нигде больше
    # не показан) -- регресс рабочей защиты в мёртвую. ФИКС: причина
    # блока ВСЕГДА дублируется в additionalContext (тот же
    # hookSpecificOutput) -- если deny-канал мёртв на харнессе,
    # additionalContext всё равно долетает до модели видимым
    # предупреждением, а не тишиной. additionalContext несёт ТУ ЖЕ
    # строку (MSG_JOURNAL_BLOCK), что и permissionDecisionReason;
    # прочие независимо сработавшие WARN-классы (а)/(б)/(в) того же
    # вызова добавляются РЯДОМ (не затирают причину блока) --
    # формулировка "не блокирует" в их части верна ИМЕННО для них,
    # общий блок вызова идёт по отдельной, независимой причине.
    if _is_journal_bypass(command):
        other_warn = _collect_warn_classes(command)
        context_parts = [MSG_JOURNAL_BLOCK] + other_warn
        return 0, {
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "permissionDecision": "deny",
                "permissionDecisionReason": MSG_JOURNAL_BLOCK,
                "additionalContext": "Командная гигиена: " + "; ".join(context_parts),
            }
        }

    triggered = _collect_warn_classes(command)
    if not triggered:
        return 0, None

    context = "Командная гигиена (WARN, не блокирует): " + "; ".join(triggered)
    # B1 (critic t-177): ключа permissionDecision здесь НЕТ НАМЕРЕННО --
    # "allow" авто-аппрувил бы флагнутую (грязную) команду, подавляя
    # permission-prompt оператора; additionalContext доставляется модели
    # и без него, а решение о разрешении остаётся штатному permission-пути.
    return 0, {
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "additionalContext": context,
        }
    }


