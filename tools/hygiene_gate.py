_CD_PREFIX_V5_CONTINUATION_RE = re.compile(r"(?:&&|;|\n)(.*)$", re.DOTALL)


def _is_cd_prefix_v5(command: str) -> bool:
    if not CD_PREFIX_START_RE.match(command):
        return False
    m = _CD_PREFIX_V5_CONTINUATION_RE.search(command)
    if not m:
        return False
    return bool(m.group(1).strip())


