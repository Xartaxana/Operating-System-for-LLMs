_PAREN_PREFIX_RE = re.compile(r"^\s*\([^)]*\)")
_JUNK_PREFIX_RE = re.compile(r"^[\s*:\-\u2014\u00ab\u00bb\"']+")
_TOKEN_SEPARATOR_RE = re.compile(r"[;,\n]")
# F-59 подкласс 3 (2026-08-10): backtick "`" добавлен в _EDGE_TRIM_CHARS
# ниже -- тот же класс markdown-декорации, что кавычки/ёлочки уже там
# снимаются (см. "Рационал ДО region-aware версии" выше, "F-59 ПОДКЛАСС
# 3"). _TRAILING_TRIM_CHARS добавляет ПОВЕРХ них хвостовую точку конца
# предложения (rstrip-only, ведущая точка защищена от гипотетического
# относительного dot-пути) -- собственное инженерное решение,
# задокументировано, не угадано молча.
_PROSE_TAIL_SEP = " \u2014 "  # пробел-эмтире-пробел -- см. "Рационал ДО region-aware версии" выше, п.3

_EDGE_TRIM_CHARS = "\"'`()[]{}\u00ab\u00bb\u201e\u201c\u201d"
_TRAILING_TRIM_CHARS = _EDGE_TRIM_CHARS + "."

# П3 (батч после калибровки №6) -- многострочный owns-блок.
_BULLET_PREFIX_RE = re.compile(r"^\s*[-*•]\s+")
# Пересдача (блокер 2): номерованный список ("1. путь" / "2) путь")
# тоже распознаётся как буллет-форма продолжения (не-блокер (а)).
_NUMBERED_PREFIX_RE = re.compile(r"^\s*\d+[.)]\s+")
# Закрытый список секций манифеста (R11 CLAUDE.md кита): given/дано,
# owns, non-goals, handoff -- опциональный markdown `**` перед словом.
_SECTION_HEADER_STOP_RE = re.compile(
    r"^\s*(?:\*\*)?(given|дано|owns|non-goals|handoff)\b", re.IGNORECASE
)
# Пересдача (блокер 2): всё ДО начала совпадения owns-маркера обязано
# быть только пробелами + опциональным буллетом + опциональным
# markdown `**` -- иначе строка маркера НЕ декларация, а проза со
