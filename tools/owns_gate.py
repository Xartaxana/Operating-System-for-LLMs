# форма уже поддерживает через _TOKEN_SEPARATOR_RE (не режущий по
# пробелу вовсе, см. докстринг модуля, "ИЗВЛЕЧЕНИЕ", п.3-4), но
# однострочный путь ЗАВЕДОМО не содержит `;`/`,`/перевода строки --
# продолжение таких гарантий не имеет (единственный разделитель токенов
# там -- пробел), поэтому кавычка/бэктик/ёлочка нужны как ЯВНЫЙ
# ограничитель, чтобы путь с пробелом внутри не обрывался на первом же
# пробеле.
_QUOTE_OPEN_TO_CLOSE = {"\"": "\"", "'": "'", "`": "`", "\u00ab": "\u00bb"}


def _first_raw_token(body: str) -> str:
    """Сырой (необрезанный) первый токен body -- ОБЫЧНО первый
    пробельный токен (body.split(None, 1)[0]), НО если body начинается
    с символа-открывашки из _QUOTE_OPEN_TO_CLOSE, ищется ПАРНЫЙ
    закрывающий символ дальше в строке -- если найден, возвращается ВСЁ
    между ними ВКЛЮЧИТЕЛЬНО (кавычки/бэктик сняты позже _clean_token,
    он уже входит в _EDGE_TRIM_CHARS) -- пробелы ВНУТРИ сохраняются
    (прецедент "D:/AI CRM/x/AGENTS.md"). Закрывающий символ не найден --
    фоллбек на обычное разбиение по пробелу (не ломает старое
    поведение на незакрытой кавычке)."""
    if body and body[0] in _QUOTE_OPEN_TO_CLOSE:
        close_char = _QUOTE_OPEN_TO_CLOSE[body[0]]
        close_idx = body.find(close_char, 1)
        if close_idx != -1:
            return body[: close_idx + 1]
    return body.split(None, 1)[0]


def _first_token_path(line: str):
    """Пересдача (не-блокер (а)): ПЕРВЫЙ токен строки продолжения
    (после снятия буллета `- `/`* `/`• ` ИЛИ номера списка `1.`/`2)`),
    если он валиден по _is_continuation_path_token -- прозаический
    хвост после первого токена ИГНОРИРУЕТСЯ (не склеивается с путём
    через отсутствие запятой-разделителя). F-59 подкласс 3
    (2026-08-10): "первый токен" теперь ищется через _first_raw_token
    -- ОБЫЧНО первый пробельный, НО если токен открыт
    кавычкой/бэктиком/ёлочкой, берётся ВСЁ до парного закрытия
    (пробелы внутри кавычек больше не режут путь пополам). None --
    строка не разбирается как путь продолжения (конец блока)."""
    body = _BULLET_PREFIX_RE.sub("", line, count=1)
    body = _NUMBERED_PREFIX_RE.sub("", body, count=1)
    body = body.strip()
    if not body:
        return None
    first_raw = _first_raw_token(body)
    tok = _clean_token(first_raw)
    if tok and _is_continuation_path_token(tok):
        return tok
    return None


def _paths_from_continuation(lines: list, start_idx: int) -> list:
    """П3: читает lines[start_idx:] как продолжение owns-блока -- см.
    докстринг модуля "МНОГОСТРОЧНЫЙ OWNS-БЛОК" за полное обоснование
    стоп-условий и предела. [] на: пустой первой строке, строке новой
    секции манифеста, первой строке без path-токена (_first_token_path),
    ИЛИ на упоре в CONTINUATION_LINE_LIMIT с блоком, ещё продолжавшимся
    бы дальше. Каждая строка блока даёт РОВНО один путь (первый
    валидный токен) -- см. докстринг модуля "ПЕРЕСДАЧА", п.2."""
    collected = []
    idx = start_idx
    n = len(lines)
    lines_consumed = 0
    while idx < n:
        line = lines[idx]
        if line.strip() == "":
            break
        if _SECTION_HEADER_STOP_RE.match(line):
            break
        path = _first_token_path(line)
        if path is None:
            break
        if lines_consumed >= CONTINUATION_LINE_LIMIT:
            # Предел ДОСТИГНУТ, а блок ЕЩЁ продолжался бы (эта строка
            # тоже валидна) -- упор в предел, не тихое усечение (см.
            # докстринг модуля, "ПРЕДЕЛ 40 СТРОК").
            return []
        collected.append(path)
        lines_consumed += 1
        idx += 1
    return collected


