def _normalize_owns_set(owns) -> set:
    """Множество normalize_path()-нормализованных путей записи/нового
    диспатча -- см. "УЗЕЛ I" выше, "НОРМАЛИЗАЦИЯ ВЛОЖЕННОСТИ". Нестроковые
    элементы и элементы, давшие пустую строку после нормализации,
    отбрасываются молча (fail-open, тот же принцип, что остальной
    модуль)."""
    if not isinstance(owns, list):
        return set()
    result = set()
    for p in owns:
        if not isinstance(p, str):
            continue
        norm = normalize_path(p)
        if norm:
            result.add(norm)
    return result


def _is_own_session(rec: dict, session_key) -> bool:
    """К3/FAIL-CLOSED (edge спеки узла I): session_key записи ОБЯЗАН
    быть непустым И буквально равен session_key нового диспатча --
    отсутствующий/None session_key записи ВСЕГДА трактуется как ЧУЖАЯ
    сессия (никогда не своя), см. "УЗЕЛ I" выше, "FAIL-CLOSED НА ЧУЖОЙ
    СЕССИИ"."""
    rec_session = rec.get("session_key")
    if rec_session is None:
        return False
    return rec_session == session_key


def _is_self_retry_record(rec: dict, session_key, new_owns_normalized: set) -> bool:
    """К1 (узел I, t-587): True -- запись ИСКЛЮЧАЕТСЯ из warn целиком
    (пересдача той же сессии, не параллельный конфликт) -- см. блок
    докстринга "УЗЕЛ I" выше за полное обоснование, названный риск и
    edge-случаи (пустой owns, отсутствующий session_key)."""
    if not _is_own_session(rec, session_key):
        return False
    rec_owns_normalized = _normalize_owns_set(rec.get("owns"))
    if not rec_owns_normalized:
        return False  # EDGE: пустой owns записи -- не подмножество ничего (см. "УЗЕЛ I")
    return rec_owns_normalized.issubset(new_owns_normalized)


def _find_overlaps(new_paths: list, records: list, session_key) -> list:
    """F4: dedup by NEW PATH, not by (path, record) pair -- see
    "Ratsional DO region-aware versii" above, "DEDUPLIKATSIYA WARN".
    Returns [(path, [(ts, description, same_session_bool), ...]), ...].

    УЗЕЛ I (t-587, К1): записи, распознанные _is_self_retry_record() как
    ПЕРЕСДАЧА ТОЙ ЖЕ сессии, исключаются из сверки ЦЕЛИКОМ, ДО per-path
    overlap-проверки ниже -- см. блок докстринга "УЗЕЛ I" перед этой
    функцией за полное обоснование, названный риск и edge-случаи.
    Частичное пересечение (К2) и чужая сессия (К3) через этот фильтр НЕ
    проходят -- остаются кандидатами обычной per-path проверки."""
    new_owns_normalized = _normalize_owns_set(new_paths)
    candidate_records = [
        rec for rec in records
        if not _is_self_retry_record(rec, session_key, new_owns_normalized)
    ]
    grouped = []
    for p in new_paths:
        matches = []
        for rec in candidate_records:
            rec_owns = rec.get("owns") or []
            if any(paths_overlap(p, existing) for existing in rec_owns):
                same_session = rec.get("session_key") == session_key
                matches.append((rec.get("ts"), rec.get("description") or "", same_session))
        if matches:
            grouped.append((p, matches))
    return grouped


def _format_mention(ts, desc, same_session: bool) -> str:
    tag = (
        "параллельный диспатч этой же сессии"
        if same_session
        else "другая сессия (класс D-0060)"
    )
    return f"{ts} \u00ab{_truncate(desc)}\u00bb ({tag})"


def _format_path_line(p: str, matches: list) -> str:
    shown = matches[:2]
    mentions = "; ".join(_format_mention(ts, desc, same) for ts, desc, same in shown)
    extra = len(matches) - len(shown)
    if extra > 0:
        mentions += f"; и ещё {extra}"
    return f"путь {p} пересекается с {mentions}"


