def _paths_from_line(line: str, marker_end: int) -> list:
    """Общий хвост обоих проходов отбора: от конца совпадения маркера
    срезается мусор (_strip_owns_marker_junk), остаток токенизируется и
    фильтруется is_path_token -- см. "Рационал ДО region-aware версии"
    выше, "ИЗВЛЕЧЕНИЕ OWNS-ПУТЕЙ", пп.2-5."""
    remainder = _strip_owns_marker_junk(line[marker_end:])
    tokens = split_and_clean_tokens(remainder)
    return [t for t in tokens if is_path_token(t)]


def _is_owns_declaration_line(line: str, marker_start: int, marker_end: int) -> bool:
    """Пересдача (блокер 2): True, только когда строка маркера сама --
    owns-декларация, а не проза со словом "owns" внутри предложения --
    см. "Рационал ДО region-aware версии" выше, "ПЕРЕСДАЧА" за полный
    разбор. Вызывается ТОЛЬКО когда _paths_from_line() уже вернула []
    для этой строки -- решает, стоит ли пробовать continuation ниже,
    или пропустить эту строку целиком (проза не хайджекает настоящую
    декларацию, которая может быть НИЖЕ)."""
    prefix = line[:marker_start]
    if not _DECLARATION_PREFIX_RE.match(prefix):
        return False
    remainder_after_junk = _strip_owns_marker_junk(line[marker_end:])
    return remainder_after_junk.strip() == ""


