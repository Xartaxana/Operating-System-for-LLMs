def _load_live_records(registry_path: Path, cwd, now: datetime) -> list:
    """Fail-open: файл отсутствует / строка битая / поля неверного
    типа -- запись/строка молча пропускается, остальные читаются как
    обычно. Область (F2) -- ОДИНАКОВЫЙ cwd (буквальное равенство
    строк), НЕ session_key -- session_key внутри записи остаётся
    только для МЕТКИ в сообщении, см. _find_overlaps."""
    if registry_path is None or not registry_path.exists():
        return []
    try:
        raw = registry_path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return []

    records = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rec = json.loads(line)
        except Exception:
            continue
        if not isinstance(rec, dict):
            continue
        if rec.get("cwd") != cwd:
            continue
        ts_str = rec.get("ts")
        if not isinstance(ts_str, str):
            continue
        try:
            rec_ts = datetime.strptime(ts_str, _TS_FORMAT)
        except Exception:
            continue
        delta = (now - rec_ts).total_seconds()
        if delta < 0 or delta > WINDOW_SECONDS:
            continue
        owns = rec.get("owns")
        if not isinstance(owns, list):
            continue
        records.append(rec)
    return records


