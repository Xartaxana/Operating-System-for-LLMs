# --- нормализация и сверка путей (общий код с owns_verify.py) --------


def normalize_path(p: str) -> str:
    """.lower(), \\ -> /, срез хвостовых / -- см. "Рационал ДО
    region-aware версии" выше, "СЕМАНТИКА ПЕРЕСЕЧЕНИЯ ПУТЕЙ"."""
    if not isinstance(p, str):
        return ""
    p = p.strip().lower().replace("\\", "/")
    while len(p) > 1 and p.endswith("/"):
        p = p[:-1]
    return p


def paths_overlap(a: str, b: str) -> bool:
    """Равенство / вложенность по границе сегмента / fnmatch в любую
    сторону при наличии глоба -- см. "Рационал ДО region-aware версии"
    выше, "СЕМАНТИКА ПЕРЕСЕЧЕНИЯ ПУТЕЙ" за обоснование fnmatchcase."""
    na, nb = normalize_path(a), normalize_path(b)
    if not na or not nb:
        return False
    if na == nb:
        return True
    if na.startswith(nb + "/") or nb.startswith(na + "/"):
        return True
    if "*" in na or "*" in nb:
        if fnmatch.fnmatchcase(nb, na) or fnmatch.fnmatchcase(na, nb):
            return True
    return False


