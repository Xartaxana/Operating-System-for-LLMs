def _region_at(scan_result, offset: int):
    """bisect по scan_result.regions -- та же схема, что md_regions.
    kind_at(), но возвращает ЦЕЛЫЙ Region (нужен .unterminated для
    полярности незакрытого фенса, см. _is_quoted)."""
    regions = scan_result.regions
    if not regions:
        return None
    starts = [r.start for r in regions]
    idx = bisect.bisect_right(starts, offset) - 1
    if idx < 0:
        return None
    region = regions[idx]
    if region.start <= offset < region.end:
        return region
    return None


def _is_quoted(region) -> bool:
    """Полярность "цитата" ЕДИНАЯ для всех веток узла C -- см. докстринг
    модуля. region is None (конец текста / вне покрытия) -> НЕ цитата
    (прозовый дефолт). Незакрытый fenced -> НЕ цитата (ПЕРЕД любой
    другой веткой -- та же приоритетная форма, что negative_lint.
    _classify правило 1, "неоднозначность не расширяет зону молчания").
    Иначе: fenced ИЛИ blockquote в kinds -> цитата; инлайн-код и проза --
    НЕ цитата (учитываются наравне -- W1 "бэктики не гасят")."""
    if region is None:
        return False
    if KIND_FENCED in region.kinds and region.unterminated:
        return False
    if KIND_FENCED in region.kinds or KIND_BLOCKQUOTE in region.kinds:
        return True
    return False


_QUOTE_TRIGGER_CHARS = "`>~"


def _prompt_has_quote_trigger(prompt: str) -> bool:
    """И-1 предфильтр, половина (б): без одного из этих символов нигде в
    тексте НИ ОДИН регион не может быть fenced/blockquote (та же фактическая
    основа, что md_regions._no_markers_whole_text() использует внутри
    scan() -- см. его докстринг)."""
    return any(ch in prompt for ch in _QUOTE_TRIGGER_CHARS)


def _line_start_offsets(text: str) -> list:
    """Смещения начала каждой строки text.splitlines() в СИМВОЛАХ исходного
    текста -- образец tools/negative_lint.py._line_start_offsets."""
    offsets = []
    pos = 0
    for wt in text.splitlines(keepends=True):
        offsets.append(pos)
        pos += len(wt)
    return offsets


def _region_aware_write_indicator_present(prompt: str, scan_result) -> bool:
    """B2-write (Ф3а): True, если ХОТЯ БЫ ОДНО совпадение WRITE_INDICATORS_RE
    лежит ВНЕ цитаты. scan_result is None -> И-0 фоллбек, bare bool(search())
    -- байт-в-байт живое поведение."""
    if scan_result is None:
        return bool(WRITE_INDICATORS_RE.search(prompt))
    for m in WRITE_INDICATORS_RE.finditer(prompt):
        if not _is_quoted(_region_at(scan_result, m.start())):
            return True
    return False


def _region_aware_owns_declaration_has_path_token(prompt: str, scan_result) -> bool:
    """B2-write (Ф3а), региональная версия owns_declaration_has_path_token()
    выше -- ТОТ ЖЕ алгоритм построчного сканирования (маркер -> тот же
    строке путь ИЛИ следующая строка-продолжение), с ОДНИМ добавлением:
    OWNS_WORD_RE-совпадение, лежащее В ЦИТАТЕ, пропускается целиком (не
    считается декларацией -- "цитируемая декларация не включает проверку
    2"). scan_result is None -> И-0 фоллбек на bare owns_declaration_
    has_path_token(prompt), байт-в-байт живое поведение."""
    if scan_result is None:
        return owns_declaration_has_path_token(prompt)
    if not isinstance(prompt, str) or not prompt:
        return False
    lines = prompt.splitlines()
    offsets = _line_start_offsets(prompt)
    for i, line in enumerate(lines):
        m = OWNS_WORD_RE.search(line)
        if not m:
            continue
        marker_offset = offsets[i] + m.start()
        if _is_quoted(_region_at(scan_result, marker_offset)):
            continue  # Ф3а: цитируемая owns-декларация не включает проверку 2
        if _owns_region_has_path_token(line[m.end():]):
            return True
        prefix = line[: m.start()]
        remainder = line[m.end():]
        if not _OWNS_DECLARATION_PREFIX_RE.match(prefix):
            continue
        if not _OWNS_MARKER_JUNK_ONLY_RE.match(remainder):
            continue
        if i + 1 >= len(lines):
            continue
        cont = lines[i + 1]
        if cont.strip() == "" or _OWNS_SECTION_STOP_RE.match(cont):
            continue
        if _owns_region_has_path_token(cont):
            return True
    return False


def _region_aware_is_write(prompt: str) -> bool:
    """decide()'s B2-write вызывает ЭТУ функцию (заменяет live :730-732
    целиком). И-1 двухчастный предфильтр: (а) bare-маркерный хит (та же
    пара предикатов, что и живой decide() уже вычисляет сегодня) -- ничего
    не найдено -> False, scan() не зовётся; (б) в тексте нет ни одного
    цитатного символа -- фильтровать нечего, bare-результат (True, раз
    дошли сюда) возвращается напрямую, scan() не зовётся. Только когда
    ОБА условия истинны -- зовём _safe_scan() РОВНО один раз (C9)."""
    bare_write = bool(WRITE_INDICATORS_RE.search(prompt))
    bare_owns = owns_declaration_has_path_token(prompt)
    if not (bare_write or bare_owns):
        return False
    if not _prompt_has_quote_trigger(prompt):
        return True
    scan_result = _safe_scan(prompt)
    if scan_result is None:
        return True  # И-0: тот же bare-результат, что дал True выше
    return _region_aware_write_indicator_present(
        prompt, scan_result
    ) or _region_aware_owns_declaration_has_path_token(prompt, scan_result)


