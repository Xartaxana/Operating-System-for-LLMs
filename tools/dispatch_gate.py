def decide(payload: dict) -> tuple[int, str]:
    """Чистая логика решения, без I/O -- тот же контракт, что живой
    dispatch_gate.decide()."""
    tool_name = payload.get("tool_name")
    if tool_name not in ("Task", "Agent"):
        return 0, ""

    tool_input = payload.get("tool_input") or {}
    subagent_type = tool_input.get("subagent_type")
    prompt = tool_input.get("prompt") or ""
    description = tool_input.get("description")

    if subagent_type == "builder":
        # B1 (live :721-723) -- НЕ ЗАТРОНУТА (Ф1а).
        if not DOD_MARKERS_RE.search(prompt):
            return 2, BLOCK_MESSAGE_NO_DOD

        # B2-write (Ф3а) -- ЕДИНСТВЕННАЯ регионально-фильтрованная ветка.
        is_write = _region_aware_is_write(prompt)
        if is_write:
            # B2-manifest (live :737-741) -- НЕ ЗАТРОНУТА (Ф4а): given/owns
            # ищутся тем же bare-regex'ом, что и живой файл, цитируемая
            # манифест-декларация по-прежнему снимает блок (см.
            # manifest_quoted_warn ниже за WARN-слой на этом направлении).
            has_manifest = bool(MANIFEST_GIVEN_RE.search(prompt)) and bool(
                OWNS_WORD_RE.search(prompt)
            )
            if not has_manifest:
                return 2, BLOCK_MESSAGE_NO_MANIFEST

    # B3 (live :743-745) -- структурное поле, сканер НЕ применяется.
    if description is not None:
        if not LABEL_MODEL_PREFIX_RE.search(description):
            return 2, BLOCK_MESSAGE_NO_LABEL

    return 0, ""


