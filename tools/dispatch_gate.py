def _truncate_snippet(s: str, max_len: int = _QUOTED_SNIPPET_MAX_LEN) -> str:
    s = s.strip()
    if len(s) > max_len:
        return s[:max_len] + "…"
    return s


def dod_quoted_warn(payload: dict) -> str:
    """"" -- нечего предупреждать (не Task/Agent, не builder, prompt
    отсутствует/пустой, нет ни одного DoD-совпадения, нет цитатного
    символа в тексте вовсе, модуль недоступен/degraded, все совпадения
    ИМЕЮТ хотя бы одно НЕцитируемое). Иначе -- ВСЕ совпадения
    DOD_MARKERS_RE лежат в fenced/blockquote (C4). ЧИСТО информационный
    слой, симметричный given_path_warn/role_type_warn -- НЕ участвует в
    exit_code, вызывается ТОЛЬКО из main(), ТОЛЬКО когда decide() уже
    вернула (0, "") (C7)."""
    try:
        if not isinstance(payload, dict):
            return ""
        if payload.get("tool_name") not in ("Task", "Agent"):
            return ""
        tool_input = payload.get("tool_input") or {}
        if not isinstance(tool_input, dict):
            return ""
        if tool_input.get("subagent_type") != "builder":
            return ""
        prompt = tool_input.get("prompt")
        if not isinstance(prompt, str) or not prompt:
            return ""
        matches = list(DOD_MARKERS_RE.finditer(prompt))
        if not matches:
            return ""  # И-1: ни одного DoD-совпадения -- сканировать нечего
        if not _prompt_has_quote_trigger(prompt):
            return ""  # И-1: нет цитатных символов -- ничто не может быть quoted
        scan_result = _safe_scan(prompt)
        if scan_result is None:
            return ""  # И-0: новый слой -- без региона предупреждать нечего
        if not all(_is_quoted(_region_at(scan_result, mm.start())) for mm in matches):
            return ""
        preview = _truncate_snippet(matches[0].group(0))
        return DOD_QUOTED_WARN_MESSAGE.format(preview=preview)
    except Exception:
        return ""


def manifest_quoted_warn(payload: dict) -> str:
    """"" -- нечего предупреждать (симметрично dod_quoted_warn выше).
    Иначе -- ВСЕ совпадения MANIFEST_GIVEN_RE лежат в цитате, ИЛИ ВСЕ
    совпадения OWNS_WORD_RE лежат в цитате (given проверяется первым --
    порядок совпадает с decide()'s has_manifest = given AND owns, C3).
    scan() зовётся НЕ БОЛЕЕ ОДНОГО раза (И-1) -- считается ОДИН раз и
    используется для обеих проверок."""
    try:
        if not isinstance(payload, dict):
            return ""
        if payload.get("tool_name") not in ("Task", "Agent"):
            return ""
        tool_input = payload.get("tool_input") or {}
        if not isinstance(tool_input, dict):
            return ""
        if tool_input.get("subagent_type") != "builder":
            return ""
        prompt = tool_input.get("prompt")
        if not isinstance(prompt, str) or not prompt:
            return ""
        given_matches = list(MANIFEST_GIVEN_RE.finditer(prompt))
        owns_matches = list(OWNS_WORD_RE.finditer(prompt))
        if not given_matches and not owns_matches:
            return ""  # И-1: ни given, ни owns -- сканировать нечего
        if not _prompt_has_quote_trigger(prompt):
            return ""  # И-1: нет цитатных символов
        scan_result = _safe_scan(prompt)
        if scan_result is None:
            return ""  # И-0: новый слой -- без региона предупреждать нечего
        if given_matches and all(
            _is_quoted(_region_at(scan_result, mm.start())) for mm in given_matches
        ):
            return MANIFEST_QUOTED_WARN_MESSAGE.format(marker="given/дано")
        if owns_matches and all(
            _is_quoted(_region_at(scan_result, mm.start())) for mm in owns_matches
        ):
            return MANIFEST_QUOTED_WARN_MESSAGE.format(marker="owns")
        return ""
    except Exception:
        return ""


# --- КРИТИК-ФИКС 2 (узел C, t-529, решение Lead: "сигналить флип, не
# молчать") ------------------------------------------------------------
# ДЫРА, найденная критиком: manifest_quoted_warn() выше требует ХОТЯ БЫ
# ОДНО совпадение MANIFEST_GIVEN_RE ИЛИ OWNS_WORD_RE, чтобы иметь что
# флагировать. Но есть путь к молчаливому снятию блока БЕЗ единого
# манифест-маркера вовсе: write-глагол (WRITE_INDICATORS_RE) лежит
# ТОЛЬКО в fenced/blockquote, given/owns в тексте ОТСУТСТВУЮТ вовсе --
# bare is_write == True (live блокирует, exit 2), региональный is_write
# == False (Ф3а фильтрует единственный сигнал) -> сиблинг тихо снимает
# блок (exit 0), а dod_quoted_warn/manifest_quoted_warn ОБА молчат (нет
# DoD/given/owns совпадений вовсе -- нечего флагировать). Это нарушение
# Ф1а ("строже -- только через WARN") в его СЛАБОЙ форме: сам флип
# СНЯТИЯ блока -- легальное направление (Ф3а), но он не должен быть
# НЕМЫМ -- решение Lead: сигналить сам факт флипа.
WRITE_QUOTED_WARN_MESSAGE = (
    "WRITE-QUOTED WARN: единственный найденный write-признак диспатча "
    "(глагол записи/owns-декларация) лежит внутри цитаты/фенса — "
    "региональный фильтр СНЯЛ блок проверки 2 (Ф3а), манифест-маркеры "
    "(given/owns) в тексте отсутствуют вовсе — не молчаливый пропуск: "
    "живой файл заблокировал бы этот же диспатч (D-0073) — сверь вручную"
)


def write_quoted_warn(payload: dict) -> str:
    """"" -- нечего предупреждать (не Task/Agent, не builder, prompt
    отсутствует/пустой, bare is_write не был True -- нет флипа возможного
    вовсе, ЛЮБОЙ манифест-маркер (given ИЛИ owns) присутствует хоть где-то
    -- этот случай уже флагует manifest_quoted_warn/C3, здесь молчим,
    чтобы не задваивать сообщение, региональный is_write остался True --
    флипа не произошло). Иначе -- bare is_write был True, региональный
    стал False, манифест-маркеров нет вовсе -- Ф3а СНЯЛ блок МОЛЧА;
    этот слой сигналит сам факт флипа (решение Lead, критик-фикс 2)."""
    try:
        if not isinstance(payload, dict):
            return ""
        if payload.get("tool_name") not in ("Task", "Agent"):
            return ""
        tool_input = payload.get("tool_input") or {}
        if not isinstance(tool_input, dict):
            return ""
        if tool_input.get("subagent_type") != "builder":
            return ""
        prompt = tool_input.get("prompt")
        if not isinstance(prompt, str) or not prompt:
            return ""
        bare_is_write = bool(WRITE_INDICATORS_RE.search(prompt)) or owns_declaration_has_path_token(
            prompt
        )
        if not bare_is_write:
            return ""
        if MANIFEST_GIVEN_RE.search(prompt) or OWNS_WORD_RE.search(prompt):
            return ""  # манифест-маркер есть -- покрыто manifest_quoted_warn (C3)
        if _region_aware_is_write(prompt):
            return ""  # флипа нет -- региональный тоже True, decide() блокирует как обычно
        return WRITE_QUOTED_WARN_MESSAGE
    except Exception:
        return ""


def _reconfigure_stderr_utf8():
    try:
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass


def _reconfigure_stdout_utf8():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass


def main() -> int:
    _reconfigure_stderr_utf8()

    raw_bytes = sys.stdin.buffer.read()
    raw = raw_bytes.decode("utf-8", errors="replace")
    try:
        payload = json.loads(raw)
    except Exception:
        return 0

    exit_code, message = decide(payload)
    if exit_code == 2:
        sys.stderr.write(message + "\n")
        return 2  # C7: ни один WARN-слой ниже не исполняется на блоке

    try:
        warn_given = given_path_warn(payload)
    except Exception:
        warn_given = ""
    try:
        warn_role = role_type_warn(payload)
    except Exception:
        warn_role = ""
    try:
        warn_dod_quoted = dod_quoted_warn(payload)
    except Exception:
        warn_dod_quoted = ""
    try:
        warn_manifest_quoted = manifest_quoted_warn(payload)
    except Exception:
        warn_manifest_quoted = ""
    try:
        warn_write_quoted = write_quoted_warn(payload)
    except Exception:
        warn_write_quoted = ""

    # C6: порядок given-path/role-type НЕ тронут (given первым); новые
    # слои этого узла -- В ХВОСТ существующего списка (критик-фикс 2:
    # write_quoted_warn -- САМЫЙ новый слой, в самый хвост).
    warn_parts = [
        w
        for w in (
            warn_given,
            warn_role,
            warn_dod_quoted,
            warn_manifest_quoted,
            warn_write_quoted,
        )
        if w
    ]
    if warn_parts:
        _reconfigure_stdout_utf8()
        output = {
            "hookSpecificOutput": {
                "hookEventName": "PreToolUse",
                "additionalContext": "\n\n".join(warn_parts),
            }
        }
        sys.stdout.write(json.dumps(output, ensure_ascii=False) + "\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
