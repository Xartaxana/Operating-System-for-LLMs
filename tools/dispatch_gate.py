    missing = []
    for tok, is_abs in candidates:
        if is_abs:
            if not _is_under_root(tok, repo_root):
                continue
            exists = os.path.exists(tok)
        else:
            exists = os.path.exists(os.path.join(repo_root, tok))
        if not exists:
            missing.append(tok)
    return format_given_path_warn(missing)


