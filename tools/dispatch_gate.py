# 1 (DoD) -> 2 (write/manifest) -> 3 (лейбл) НЕ МЕНЯЕТСЯ. B1 (:721-723)
# и B2-manifest (:737-741) -- СКОПИРОВАНЫ БЕЗ ИЗМЕНЕНИЙ (Ф1а/Ф4а). Единственная
# правка -- вычисление is_write внутри B2 заменено на региональное
# (Ф3а, единственное место, где сиблинг может дать ДРУГОЙ exit_code,
# чем живой файл -- см. C3).
