_PATH_TOKEN_WIN_ABS_RE = re.compile(r"^[A-Za-z]:[\\/]+[^\\/\s]")
_PATH_TOKEN_POSIX_ABS_RE = re.compile(r"^/+[^/\s]")


def is_path_like_token(tok) -> bool:
    """ЕДИНАЯ точка правды "токен похож на путь": Windows-абсолютный
    (буква диска + `:` + слэш), POSIX-абсолютный (начинается с `/`),
    ЛИБО глоб, несущий И "*", И слэш (`/` или `\\`). Голое "*" БЕЗ
    слэша (напр. markdown "**жирный**", "**Внимание**:") НЕ считается
    путём -- F6 (критик, 2026-08-10): прежний owns_gate.is_path_token()
    засчитывал ЛЮБОЙ токен с "*" где угодно, и живой sidecar
    owns_gate зарегистрировал прозу "обратная сторона.** Пишущий
    диспатч" как owns-путь на диспатче этого же ревью. Используется
    (а) owns_declaration_has_path_token() ниже; (б) owns_gate.py
    (импорт, через живое имя dispatch_gate после посадки, заменяет его
    прежний локальный is_path_token()).

    ROOT-ONLY GUARD (найдено эмпирически, фикс этой правки): оба
    абсолютных regex'а требуют >=1 символа СЕГМЕНТА (не слэш, не
    пробел) СРАЗУ ПОСЛЕ корневого слэша -- голый корень БЕЗ сегмента
    пути ("/", "//", "///", "D:\\", "D:/") путём не считается. До
    фикса `^/`/`^[A-Za-z]:[\\/]` матчили и голый корень: "/" проходил
    как валидный owns-путь, normalize_path("/")=="/" самопересекался с
    любым другим стрёмным "/" (ложный "OWNS OVERLAP" на КАЖДОМ
    диспатче, несущем случайный "/"), а "D:\\"/"D:/" нормализовались в
    "d:" -- пересечение ВСЕГО диска D. Фантомный корень-без-сегмента --
    не владеемый путь ни в каком практическом смысле. Порядок проверок
    НЕ меняется: оба абсолютных regex'а по-прежнему проверяются
    ПЕРВЫМИ, до глоб-ветки ниже; глоб-ветка (голая "*" + слэш, не
    начинающаяся с диска/корня) не затронута.

    УТОЧНЕНИЕ (критик t-476): класс -- "корень БЕЗ сегмента", а не
    "ровно один корневой слэш". Поэтому `/+`/`[\\/]+` (один-и-более
    корневых слэша, затем сегмент): удвоенный корень С сегментом --
    "//foo", "//server/share", "D://x" -- ЭТО путь (сегмент есть);
    отвергается только голый корень ("/", "//", "///", "D:\\", "D:/").
    Прежняя форма `^/[^/\\s]` ошибочно роняла "//foo" (сегмент "foo"
    есть) -- расхождение с заявленным намерением, а не с классом.

    (Дословный перенос из докстринга is_path_like_token() живого
    tools/dispatch_gate.py -- критик-фикс 4, узел C, t-529.)

    Р7 УЗЛА D РЕМЕДИАЦИИ КАЛИБРОВКИ #8 (2026-08-20, "Фантомный токен",
    форма 1, решение Lead): ветка POSIX-абсолютного пути ужесточена --
    ПОМИМО совпадения с _PATH_TOKEN_POSIX_ABS_RE (корень + >=1 символ
    сегмента) токен обязан НЕ нести пробелов И нести ЛИБО расширение
    файла (`\\.[A-Za-z0-9]{1,10}` в хвосте) ЛИБО >=2 сегмента после
    корня (`/a/b` -- два сегмента, `/a` -- один). Мотив: короткие
    прозаические обрывки с одним слэшем ("смотри /etc системы",
    единичное упоминание) ложно проходили путём. ГРАНИЦА (правило 6а):
    "/etc/x" (2 сегмента, без расширения) -- True; "/a" (1 сегмент, без
    расширения) -- False (см. test_root_with_segment_absolute_token_is_
    a_path в test_dispatch_gate.py -- ЭТА правка НАРОЧНО СУЖАЕТ прежний
    пин AK2 для голых 1-сегментных POSIX-путей без расширения; см.
    докстринг того теста за перенесённые значения). Windows-ветка
    (_PATH_TOKEN_WIN_ABS_RE) и глоб-ветка (`"*" in tok`) этой формой НЕ
    затронуты -- решение называет буквально "POSIX-ветка"."""
    if not isinstance(tok, str) or not tok:
        return False
    if _PATH_TOKEN_WIN_ABS_RE.match(tok):
        return True
    if _PATH_TOKEN_POSIX_ABS_RE.match(tok):
        if " " in tok:
            return False
        has_ext = bool(re.search(r"\.[A-Za-z0-9]{1,10}$", tok))
        if has_ext:
            return True
        segments = [s for s in tok.lstrip("/\\").split("/") if s]
        return len(segments) >= 2
    return "*" in tok and ("/" in tok or "\\" in tok)


