def _paragraph_spans(prompt: str) -> list:
    """D-1 (вердикт критика t-554, 2026-08-20): АБЗАЦ = блок непустых
    строк между пустыми строками (line.strip() == "" -- разделитель).
    Возвращает список непересекающихся char-офсетов (start, end) в
    порядке возрастания -- по одному диапазону на абзац, включает
    завершающие переводы строк ВНУТРИ абзаца, НЕ включает пустые
    строки-разделители. КРАЙ (задокументирован явно, спека узла требует
    закрепить тестом): промпт БЕЗ единой пустой строки даёт РОВНО один
    span, покрывающий весь текст -- поведение п.1 (маркер освобождает
    весь промпт) для такого промпта остаётся ТЕМ ЖЕ, что было ДО этой
    правки; это ПРИНЯТО сознательно, не дефект (см. докстринг
    _tokens_outside_deploy_paragraph и тест
    test_d1_prompt_without_blank_line_marker_frees_whole_prompt)."""
    lines = prompt.splitlines(keepends=True)
    spans = []
    pos = 0
    para_start = None
    for line in lines:
        if line.strip() == "":
            if para_start is not None:
                spans.append((para_start, pos))
                para_start = None
        elif para_start is None:
            para_start = pos
        pos += len(line)
    if para_start is not None:
        spans.append((para_start, pos))
    return spans


def _paragraph_index(spans: list, offset: int):
    """Индекс абзаца (из _paragraph_spans), которому принадлежит
    offset, либо None (offset внутри пустой строки-разделителя, ДО
    первого абзаца, либо за пределами всех абзацев)."""
    if not spans:
        return None
    starts = [s for s, _ in spans]
    idx = bisect.bisect_right(starts, offset) - 1
    if idx < 0:
        return None
    start, end = spans[idx]
    if start <= offset < end:
        return idx
    return None


def _tokens_outside_deploy_paragraph(prompt: str, deploys: dict, patterns) -> set:
    """Р1 СУЖЕНО (вердикт критика t-554, 2026-08-20): множество ТОКЕНОВ
    (текст совпадения given-регексов), у которых ХОТЯ БЫ ОДНО вхождение
    лежит ВНЕ абзаца, несущего маркер внешнего деплоя (имя ключа
    `deploys` ИЛИ его путь -- те же два условия, что прежний ГЛОБАЛЬНЫЙ
    (без учёта абзаца) предикат Р1 проверял целиком по всему промпту --
    удалён батчем 2026-08-20 (t-543 follow-up) как мёртвый код после
    того, как D-1 сузил Р1 до этой, ЛОКАЛИЗОВАННОЙ по позиции, формы;
    см. комментарий на месте удалённого определения выше за историю).
    Форма -- та же, что
    _tokens_outside_owns_section() выше несёт для owns-секции ("одно
    вхождение решает"), инвертированная по смыслу: там "вне owns"
    сохраняет кандидата в проверке, здесь "вне маркерного абзаца"
    ЛИШАЕТ кандидата освобождения (_filter_given_candidates ниже читает
    эту разницу через отдельное условие, не общий предикат).

    ПОЧЕМУ НЕ ранний возврат при "маркеров вообще нет": deploys пуст ИЛИ
    ни имя, ни путь ни разу не встретились в тексте -- marker_paragraphs
    остаётся пустым множеством, и цикл по patterns ниже добавит В outside
    КАЖДЫЙ найденный токен (idx not in set() -- всегда True) -- то есть
    "нет маркера вообще" и "маркер есть, но кандидат вне его абзаца" дают
    ОДИН и тот же итог (кандидат не освобождается) через ОДИН и тот же
    путь кода, без развилки-дублёра."""
    outside = set()
    if not isinstance(prompt, str) or not prompt:
        return outside
    spans = _paragraph_spans(prompt)
    if not spans:
        return outside
    marker_paragraphs = set()
    if deploys:
        norm_prompt = prompt.replace("\\", "/").lower()
        for name, path in deploys.items():
            for m in re.finditer(r"\b" + re.escape(name) + r"\b", prompt, re.IGNORECASE):
                idx = _paragraph_index(spans, m.start())
                if idx is not None:
                    marker_paragraphs.add(idx)
            norm_path = path.replace("\\", "/").lower().rstrip("/")
            if not norm_path:
                continue
            start = 0
            while True:
                pos = norm_prompt.find(norm_path, start)
                if pos == -1:
                    break
                idx = _paragraph_index(spans, pos)
                if idx is not None:
                    marker_paragraphs.add(idx)
                start = pos + 1
    for pattern in patterns:
        for m in pattern.finditer(prompt):
            idx = _paragraph_index(spans, m.start())
            if idx not in marker_paragraphs:
                outside.add(m.group(0))
    return outside


# Закрытый список секций манифеста, R11 CLAUDE.md кита -- given/дано,
# owns, non-goals, handoff (та же форма, что owns_gate._SECTION_HEADER_
# STOP_RE уже несёт для стоп-условия многострочного owns-блока).
# D-2 (вердикт критика t-554, 2026-08-20): опциональный markdown-
# заголовок ("#{1,6}\s+") и буллет ("[-*•]\s+") добавлены ПЕРЕД "**" --
# ТА ЖЕ форма, что owns_gate._DECLARATION_PREFIX_RE уже несёт (D-0043,
# один класс, не изобретается заново). ДО этой правки owns-секция,
# объявленная заголовком ("## OWNS (...)") или буллетом ("- owns:") --
# 14 и 15 из 237 owns-несущих боевых промптов -- НЕ распознавалась ни
# здесь, ни в _OWNS_SECTION_STOP_RE ниже (WARN-слой given_path_warn
# молчал о секции; см. также _OWNS_SECTION_STOP_RE выше, тот же класс,
# тот же коммит).
# А-К4 (узел A, 2026-08-25): русские синонимы "не-цели"/"не цели"
# добавлены к уже распознаваемому английскому "non-goals" -- ДО этой
# правки регекс "non-goals" уже матчил, но _section_map() ниже сливал
# результат в общую ветку "other" (см. её докстринг за разбор).
_MANIFEST_SECTION_HEADER_RE = re.compile(
    r"^\s*(?:#{1,6}\s+)?(?:[-*•]\s+)?(?:\*\*)?(given|дано|owns|не[-\s]+цели|non-goals|handoff)\b",
    re.IGNORECASE,
)


_SECTION_BULLET_PREFIX_RE = re.compile(r"^\s*[-*•]\s+")
_SECTION_NUMBERED_PREFIX_RE = re.compile(r"^\s*\d+[.)]\s+")


def _is_owns_continuation_line(line: str) -> bool:
    """D-3 (вердикт критика t-554, 2026-08-20): предикат "строка -- ЕЩЁ
    owns-секция, а не сорвавшаяся в прозу" для _section_map() ниже --
    ТА ЖЕ форма, что owns_gate._first_token_path()/_paths_from_
    continuation() уже несут для многострочного owns-блока (буллет/
    номер списка снимается, ПЕРВЫЙ оставшийся токен обязан быть похож
    на путь) -- НЕ импорт: owns_gate ИМПОРТИРУЕТ ИЗ dispatch_gate (не
    наоборот, см. докстринг модуля "НОСИТЕЛЬ..."), обратное направление
    завело бы цикл, поэтому здесь -- локальная копия формы, тем же
    приёмом, каким _OWNS_SECTION_STOP_RE/_MANIFEST_SECTION_HEADER_RE
    уже копируют owns_gate._SECTION_HEADER_STOP_RE/_DECLARATION_PREFIX_
    RE (не новая семантика -- перенос существующей формы, D-0043).
    НОВЫЙ ЛОКАЛЬНЫЙ ХЕЛПЕР этого диспатча (носитель -- этот же модуль,
    tools/dispatch_gate.py; не механизменный путь -- часть WARN-слоя
    given_path_warn, _section_map её вызывает ТОЛЬКО из
    _filter_given_candidates, вне decide())."""
    body = _SECTION_BULLET_PREFIX_RE.sub("", line, count=1)
    body = _SECTION_NUMBERED_PREFIX_RE.sub("", body, count=1)
    body = body.strip()
    if not body:
        return False
    first = body.split(None, 1)[0]
    first = first.strip(_OWNS_TOKEN_EDGE_STRIP)
    return is_path_like_token(first)


def _section_map(prompt: str):
    """Р2: (line_start_offsets, sections) -- sections[i] -- секция
    манифеста, действующая на СТРОКЕ i ("owns"/"given"/"other"/"none",
    "none" -- ДО первого заголовка манифеста). Заголовок распознаётся в
    начале строки (после опционального markdown "**"), как и owns_gate.
    _SECTION_HEADER_STOP_RE.

    D-3 (вердикт критика t-554, 2026-08-20): у owns-секции появилась
    ВЕРХНЯЯ ГРАНИЦА -- ДО этой правки секция, открытая строкой-маркером
    "owns", тянулась до конца промпта целиком; одна прозаическая строка
    ("owns не нужен -- read-only", сама матчащая заголовок) гасила
    проверку given-путей на ВСЁМ, что ниже. Теперь, пока current ==
    "owns", КАЖДАЯ следующая строка, которая САМА не заголовок другой
    секции, обязана быть ПУСТОЙ (blank -- просто конец секции без
    смены) ЛИБО валидной строкой продолжения (_is_owns_continuation_line
    -- буллет/номер + path-подобный первый токен, форма owns_gate) --
    иначе секция закрывается ЭТОЙ ЖЕ строкой (current становится
    "other", путь на строке, гасящей секцию, снова проверяется).
    ФОРМА -- дословно owns_gate._paths_from_continuation()'s
    стоп-условия (пустая строка / секционный заголовок / не-continuation
    строка), см. докстринг _is_owns_continuation_line за обоснование
    "не импорт, а копия"."""
    lines = prompt.splitlines(keepends=True)
    offsets = []
    sections = []
    pos = 0
    current = "none"
    for line in lines:
        m = _MANIFEST_SECTION_HEADER_RE.match(line)
        if m:
            word = m.group(1).lower()
            if word == "owns":
                current = "owns"
            elif word in ("given", "дано"):
                current = "given"
            elif word == "non-goals" or word.startswith("не"):
                # А-К4 (узел A): "не-цели"/"не цели" (любой пробельный/
                # дефисный разделитель, IGNORECASE уже применён к
                # исходному матчу) -- собственная метка, не "other".
                # Симметрично given/other: секция НЕ закрывается пустой
                # строкой (нет отдельной ветки elif current=="non-goals"
                # ниже) -- держится до следующего заголовка манифеста.
                current = "non-goals"
            else:
                current = "other"
        elif current == "owns" and (line.strip() == "" or not _is_owns_continuation_line(line)):
            current = "other"  # D-3: пустая строка ЛИБО строка не продолжает owns-блок
        offsets.append(pos)
        sections.append(current)
        pos += len(line)
    return offsets, sections


def _token_occurrence_sections(prompt: str, patterns) -> dict:
    """Узел A, общая механика А-К1/А-К4/А-К6: для КАЖДОГО извлечённого
    токена (текст совпадения любого из *patterns*) -- список секций
    манифеста (см. _section_map()), в которых лежит КАЖДОЕ его
    вхождение, в порядке появления. ОДИН проход по prompt на пару
    regex'ов -- переиспользуется owns/given/non-goals предикатами ниже,
    вместо трёх отдельных сканов (важно для ReDoS/1MB-промпта из
    адверсариальной батареи -- O(n) на паттерн, не O(3n))."""
    offsets, sections = _section_map(prompt)
    occ: dict = {}
    if not offsets:
        return occ
    for pattern in patterns:
        for m in pattern.finditer(prompt):
            tok = m.group(0)
            idx = bisect.bisect_right(offsets, m.start()) - 1
            sec = sections[idx] if idx >= 0 else "none"
            occ.setdefault(tok, []).append(sec)
    return occ


def _tokens_any_in_section(occ: dict, section_name: str) -> set:
    """Токены, у которых ХОТЯ БЫ ОДНО вхождение -- в *section_name*
    ("объявлен" -- форма А-К1 для owns, А-К6 для given)."""
    return {tok for tok, secs in occ.items() if section_name in secs}


def _tokens_all_in_section(occ: dict, section_name: str) -> set:
    """Токены, у которых ВСЕ вхождения -- в *section_name* ("единственные
    вхождения" -- старая форма Р2, сохранена для non-goals, А-К4)."""
    return {tok for tok, secs in occ.items() if secs and all(s == section_name for s in secs)}


# А-К2 (форма б): "непосредственно после запускающего слова" -- окно в
# 24 символа НАЗАД от начала токена достаточно с запасом для "python "/
# "pytest " (6-7 символов) плюс несколько лишних пробелов; фиксированное
# окно (не поиск по всему префиксу) -- O(1) на вхождение, тот же ReDoS-
# мотив, что у _token_occurrence_sections выше.
_RUN_LAUNCH_PREFIX_RE = re.compile(r"(?:^|[^\w])(?:python|pytest)[ \t]+\Z")
_RUN_LAUNCH_LOOKBACK = 24


def _token_after_launch_word(prompt: str, start: int) -> bool:
    window = prompt[max(0, start - _RUN_LAUNCH_LOOKBACK):start]
    return bool(_RUN_LAUNCH_PREFIX_RE.search(window))


def _tokens_all_after_launch_word(prompt: str, patterns) -> set:
    """А-К2: токены, у которых КАЖДОЕ вхождение непосредственно следует
    за `python`/`pytest` (ровно эти два слова -- спека их и называет,
    `python3`/иные лаунчеры не добавлены самовольно)."""
    flags: dict = {}
    for pattern in patterns:
        for m in pattern.finditer(prompt):
            tok = m.group(0)
            ok = _token_after_launch_word(prompt, m.start())
            flags[tok] = flags.get(tok, True) and ok
    return {tok for tok, ok in flags.items() if ok}


# А-К3 (форма в1): метапеременная-заглушка. (1) >=2 ОДИНАКОВЫХ заглавных
# латинских ПОДРЯД, изолированных не-буквами с обеих сторон (backreference
# -- "AB" из РАЗНЫХ букв не матчит, только повтор ОДНОЙ; лукбихайнд/
# лукахед не-буква защищают от ложного срабатывания на настоящих словах
# вроде "PROCESS" -- "SS" там СРАЗУ после буквы "E", не изолирован).
# (2)/(3) `<...>`/`{...}` -- см. докстринг модуля за находку "недостижимо
# через живую экстракцию, предикат несёт форму для полноты".
_TEMPLATE_REPEAT_UPPER_RE = re.compile(r"(?<![A-Za-z])([A-Z])\1+(?![A-Za-z])")
_TEMPLATE_ANGLE_RE = re.compile(r"<[^<>]+>")
_TEMPLATE_BRACE_RE = re.compile(r"\{[^{}]+\}")


def _is_template_token(tok: str) -> bool:
    if _TEMPLATE_REPEAT_UPPER_RE.search(tok):
        return True
    if _TEMPLATE_ANGLE_RE.search(tok):
        return True
    if _TEMPLATE_BRACE_RE.search(tok):
        return True
    return False


def _split_backtick_body(tok: str) -> list:
    """K3 (docs/tasks/2026-08-25_queue8-mechbatch-spec.md): носитель --
    ВЫХОДНОЙ шаг _filter_given_candidates ниже (GIVEN_*_RE извлечения
    сами НЕ трогаются, позиционный инвариант узла A сохраняется). Тело
    извлечённого GIVEN-регексами кандидата может содержать буквальный
    бэктик (` ` `), когда между двумя бэктик-обёрнутыми путями нет
    пробельного разделителя -- _GIVEN_PATH_BODY_CHAR исключает `\\s`, но
    НЕ исключает `` ` `` -- греди-квантификатор {0,300} склеивает оба
    пути (и всё между ними) в ОДИН кандидат-токен. Фикс: тело, содержащее
    бэктик, режется по бэктикам; непустые сегменты возвращаются как
    отдельные пути. Края: тело из одних бэктиков -> пустой список (все
    части split пустые); одиночный бэктик на конце -> хвостовая пустая
    часть отбрасывается (срезается); тело без бэктика -> список из
    одного исходного тела (регресс существующих 243 тестов -- вызывающий
    код применяет эту функцию ТОЛЬКО когда "`" уже найден в tok)."""
    return [part for part in tok.split("`") if part]


def _filter_given_candidates(prompt: str, candidates: list, patterns=None, deploy_markers=None) -> list:
    """ЕДИНАЯ точка фильтрации Р1 + узел A (форма а/б/в1/в2) -- вызывается
    ПОСЛЕ извлечения кандидатов (bare ИЛИ регионально-осведомлённого), ДО
    проверки существования (позиционный инвариант, не сдвинут). НИ ОДНО
    правило не может ДОБАВИТЬ токен в missing -- только исключить из
    проверки (А-К5).

    ФИКС-РАУНД FRESHNESS Б1 (критик-гейт t-606, 2026-08-25): *patterns*
    и *deploy_markers* -- НОВЫЕ опциональные параметры, дефолт None ->
    ПРЕЖНЕЕ поведение байт-в-байт (given-пара регексов, живой
    _load_deploy_markers()) -- given_path_warn/find_missing_given_paths
    НЕ переданы новым аргументом, значит НЕ ЗАТРОНУТЫ. Мотив: freshness
    (класс в, logs-префикс) передаёт СВОИ регексы-сканеры (given-регексы
    "logs" не несут -- их популяция чужая, узел не её трогает) -- БЕЗ
    этого параметра exemption-множества ниже (given_tokens/owns_declared/
    .../deploy_outside_paragraph) считались given-регексами и НИКОГДА не
    находили logs-кандидата ни в одном вхождении, отчего Р1-ветка молча
    исключала ЛЮБОЙ logs-путь из проверки (deploy_outside_paragraph
    пуст -- "не найден снаружи маркерного абзаца" ложно читалось как
    "внутри", хотя маркера не было вовсе). freshness класса (а) передаёт
    ТРЕТИЙ регекс (FRESHNESS_CHECK_TOKEN_RE) и РАСШИРЕННЫЙ deploy_markers
    (кит/toolkit, Б2) -- populяция (в) им не трогается (свой вызов, свой
    словарь).

    K3 (докстринг _split_backtick_body выше) -- ПОСЛЕДНИЙ шаг, ПОСЛЕ
    решения об исключении: exemption-множества ниже (given_tokens/
    owns_declared/non_goals_confined/run_line_confined/
    deploy_outside_paragraph) вычисляются ПОВТОРНЫМ regex-сканом
    prompt тем же `patterns`, ключ -- буквальный ТЕКСТ regex-совпадения
    (склеенный кандидат целиком, если он склеен) -- сегмент, разрезанный
    ПО бэктику, никогда не встретится как отдельный ключ в этих
    множествах (это НЕ regex-совпадение, а его часть). Поэтому решение
    "исключить/оставить" принимается на ЦЕЛОМ (возможно склеенном)
    кандидате СНАЧАЛА, как и раньше, и ТОЛЬКО кандидат, прошедший все
    проверки без исключения, режется на бэктик-сегменты В КОНЦЕ, перед
    append в result -- разрезание не может вернуть в проверку токен,
    который exemption уже вывела из missing (А-К5 не нарушен).

    Порядок применения правил ниже НЕ влияет на результат (Р1 и правила
    узла A -- НЕЗАВИСИМАЯ конъюнкция множеств, коммутативность проверена
    тестом test_a_filter_commutative_regardless_of_check_order):

      1. А-К3 (шаблон имени) -- БЕЗУСЛОВНО, ПЕРВЫМ, given НЕ выкупает.
      2. given-выкуп (А-К6) -- токен, названный в given, минует 3-5.
      3. А-К1 (owns, форма а, Р4 -- решение Lead, см. докстринг модуля).
      4. А-К4 (non-goals, форма в2).
      5. А-К2 (строка прогона, форма б).
      6. Р1 (чужой деплой, УЗЕЛ D ремедиации калибровки #8) -- НЕ
         тронут этим диспатчем, только к относительным кандидатам
         (абсолютные вне cwd уже отсеяны выше по стеку _is_under_root).
      7. K3 (разрезание по бэктику) -- ВЫХОДНОЙ шаг, см. докстринг выше."""
    if patterns is None:
        patterns = (GIVEN_ABS_WIN_PATH_RE, GIVEN_REPO_REL_PATH_RE)
    if deploy_markers is None:
        deploy_markers = _load_deploy_markers()

    templated = {tok for tok, _ in candidates if _is_template_token(tok)}  # А-К3

    occ = _token_occurrence_sections(prompt, patterns)
    given_tokens = _tokens_any_in_section(occ, "given")  # А-К6
    owns_declared = _tokens_any_in_section(occ, "owns")  # А-К1 (новая семантика)
    non_goals_confined = _tokens_all_in_section(occ, "non-goals")  # А-К4
    run_line_confined = _tokens_all_after_launch_word(prompt, patterns)  # А-К2

    deploy_outside_paragraph = _tokens_outside_deploy_paragraph(
        prompt, deploy_markers, patterns
    )  # Р1 -- НЕ тронут узлом A (форма); ИСТОЧНИК словаря теперь параметр

    result = []
    for tok, is_abs in candidates:
        if tok in templated:
            continue  # А-К3: безусловно, given не выкупает
        if tok not in given_tokens:
            if tok in owns_declared:
                continue  # А-К1
            if tok in non_goals_confined:
                continue  # А-К4
            if tok in run_line_confined:
                continue  # А-К2
        if not is_abs and tok not in deploy_outside_paragraph:
            continue  # Р1 (сужено t-554): каждое вхождение -- в абзаце маркера деплоя
        if "`" in tok:  # K3: разрезать ТОЛЬКО прошедший все проверки кандидат
            for part in _split_backtick_body(tok):
                # F3 (ФИКС-РАУНД, docs/tasks/2026-08-25_queue8-mechbatch-
                # spec.md): сегмент, полученный разрезом по бэктику, обязан
                # ЦЕЛИКОМ (fullmatch, не search) совпасть с одним из двух
                # GIVEN-регексов извлечения -- иначе это связка/мусор
                # ("и" между двумя путями без пробела), не путь: она НЕ
                # входит ни в result (не влияет на GIVEN-PATH WARN текст),
                # ни в порог GIVEN_PATH_WARN_SUMMARY_THRESHOLD (10). Точка
                # разреза (после exemption, см. докстринг выше) НЕ сдвинута
                # -- fullmatch добавлен КАК ФИЛЬТР на уже разрезанный
                # результат, критик подтвердил позицию разреза отдельно.
                # ФИКС-РАУНД Б1: fullmatch -- ПРОТИВ *patterns* (параметр),
                # не хардкод given-регексов -- иначе freshness-кандидаты со
                # своим regex-набором теряли бы этот путь молча.
                if any(p.fullmatch(part) for p in patterns):
                    result.append((part, is_abs))
        else:
            result.append((tok, is_abs))
    return result


