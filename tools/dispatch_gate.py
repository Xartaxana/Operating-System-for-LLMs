_GIVEN_PATH_BODY_CHAR = r'[^\s"\'<>|?*{}$,;\n]'

GIVEN_ABS_WIN_PATH_RE = re.compile(
    r"(?<!\w)[A-Za-z]:[\\/]" + _GIVEN_PATH_BODY_CHAR + r"{0,300}\.[A-Za-z0-9]{1,10}\b"
)

_GIVEN_REPO_REL_PREFIX = r"(?:tools|gateway|PROCESS|docs|\.claude|\.githooks)"
GIVEN_REPO_REL_PATH_RE = re.compile(
    r"(?<![\w/\\])"
    + _GIVEN_REPO_REL_PREFIX
    + r"/"
    + _GIVEN_PATH_BODY_CHAR
    + r"{0,300}\.[A-Za-z0-9]{1,10}\b"
)

GIVEN_PATH_WARN_SUMMARY_THRESHOLD = 10


def extract_given_candidates(prompt: str) -> list:
    """Bare (не региональная) экстракция -- живая копия live :791-808 БЕЗ
    ИЗМЕНЕНИЙ: (а) И-0 фоллбек; (б) И-1 "маркерный хит" половина
    предфильтра для given_path_warn() ниже; (в) эталон в тестах
    производительности/границы {0,300} (перенесены из живой батареи)."""
    if not isinstance(prompt, str) or not prompt:
        return []
    seen_set = set()
    candidates = []
    for m in GIVEN_ABS_WIN_PATH_RE.finditer(prompt):
        tok = m.group(0)
        if tok not in seen_set:
            seen_set.add(tok)
            candidates.append((tok, True))
    for m in GIVEN_REPO_REL_PATH_RE.finditer(prompt):
        tok = m.group(0)
        if tok not in seen_set:
            seen_set.add(tok)
            candidates.append((tok, False))
    return candidates


def extract_given_candidates_region_aware(prompt: str, scan_result) -> list:
    """C1/C2: региональная версия extract_given_candidates() -- ТЕ ЖЕ
    два регекса (не изменены), но каждое совпадение проверяется на
    цитируемость своей ПОЗИЦИИ. C2 "любое вне цитаты -> проверяем":
    токен КВАЛИФИЦИРУЕТСЯ (входит в результат), если ХОТЯ БЫ ОДНО его
    вхождение НЕ в цитате -- даже если ДРУГИЕ вхождения того же токена
    цитируются. Дедуп сохраняется -- порядок результата = порядок
    ПЕРВОГО появления квалифицирующегося токена (та же семантика
    "первое появление", что и bare-версия, применённая к отфильтрованному
    подмножеству). scan_result is None -> И-0 фоллбек на bare-версию."""
    if scan_result is None:
        return extract_given_candidates(prompt)
    if not isinstance(prompt, str) or not prompt:
        return []
    order = []
    seen = {}
    for pattern, is_abs in ((GIVEN_ABS_WIN_PATH_RE, True), (GIVEN_REPO_REL_PATH_RE, False)):
        for m in pattern.finditer(prompt):
            tok = m.group(0)
            quoted = _is_quoted(_region_at(scan_result, m.start()))
            if tok not in seen:
                seen[tok] = {"is_abs": is_abs, "any_unquoted": not quoted}
                order.append(tok)
            elif not quoted:
                seen[tok]["any_unquoted"] = True
    return [(tok, seen[tok]["is_abs"]) for tok in order if seen[tok]["any_unquoted"]]


def _is_under_root(path_str: str, root: str) -> bool:
    """Живая копия live :811-821 БЕЗ ИЗМЕНЕНИЙ."""
    try:
        norm_path = os.path.normcase(os.path.normpath(path_str))
        norm_root = os.path.normcase(os.path.normpath(root))
    except Exception:
        return False
    return norm_path == norm_root or norm_path.startswith(norm_root + os.sep)


def find_missing_given_paths(prompt: str, repo_root: str) -> list:
    """Bare (не региональная) версия -- живая копия live :824-839 БЕЗ
    ИЗМЕНЕНИЙ, И-0 фоллбек given_path_warn()."""
    missing = []
    for tok, is_abs in extract_given_candidates(prompt):
        if is_abs:
            if not _is_under_root(tok, repo_root):
                continue
            exists = os.path.exists(tok)
        else:
            exists = os.path.exists(os.path.join(repo_root, tok))
        if not exists:
            missing.append(tok)
    return missing


